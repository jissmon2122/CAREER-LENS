def get_role_domain(role_title: str) -> str:
    """Resolve a role title to its canonical domain."""
    from app.services.role_taxonomy import RoleTaxonomy
    clean = (role_title or "").strip()
    if clean in RoleTaxonomy.ROLE_TAXONOMY:
        return RoleTaxonomy.ROLE_TAXONOMY[clean].get("domain", "SOFTWARE_DEVELOPMENT")
    entry = RoleTaxonomy.find_taxonomy_entry(clean)
    if entry and entry.get("domain"):
        return entry.get("domain")
    # Fuzzy pattern fallback
    clean_l = clean.lower()
    if any(k in clean_l for k in ["electric", "wireman"]):
        return "SKILLED_TRADES_ELECTRICAL"
    if any(k in clean_l for k in ["plumb", "pipe"]):
        return "SKILLED_TRADES_PLUMBING"
    if any(k in clean_l for k in ["weld"]):
        return "SKILLED_TRADES_WELDING"
    if any(k in clean_l for k in ["nurse", "nursing"]):
        return "HEALTHCARE_NURSING"
    if any(k in clean_l for k in ["account", "auditor", "cpa", "tax"]):
        return "ACCOUNTING_FINANCE"
    if any(k in clean_l for k in ["teach", "tutor", "instructor", "faculty"]):
        return "EDUCATION"
    if any(k in clean_l for k in ["ai", "machine learning", "deep learning", "nlp"]):
        return "AI_ML"
    if any(k in clean_l for k in ["data", "analytics", "bi "]):
        return "DATA_SCIENCE_ANALYTICS"
    return "SOFTWARE_DEVELOPMENT"

def get_base_benchmarks(domain: str, country: str = "IN") -> Dict[str, float]:
    """Retrieve base quantile distribution for domain and country."""
    country = (country or "IN").upper()
    if country not in CURRENCY_MAP:
        country = "IN"
    domain_data = DOMAIN_SALARY_BENCHMARKS.get(domain) or DOMAIN_SALARY_BENCHMARKS["SOFTWARE_DEVELOPMENT"]
    return domain_data.get(country) or domain_data["IN"]
